"""Generate SYNTHETIC HMO benefit documents, for testing a benefits-schedule reader.

Why these exist
---------------
`hmo_published_tiers.csv` carries four numbers per plan: the MBL and the room entitlement.
A real Summary of Benefits carries perhaps forty, and several of them bind BEFORE the MBL
does -- per-procedure sub-limits, an outpatient diagnostics ceiling, a first-year cap on
pre-existing conditions, professional fees drawn from the same pot. Our waterfall models
none of that, so on a laparoscopic cholecystectomy it can credit an HMO with ten times
what a real schedule would pay.

Reading those documents is the fix, and a reader needs documents to be tested against.
Real ones cannot go in a public repo: they are somebody's actual policy, they name a
member, and the ones circulating online are re-uploads of employer contracts.

What is real here and what is not
---------------------------------
REAL, and sourced:
  - the tier names, MBLs and room entitlements  (maxicare.com.ph, see HMO_TIERS_PROVENANCE)
  - the SHAPE of a schedule of benefits: the section order, the "subject to MBL" phrasing,
    a Special Modalities table of per-procedure caps, pre-existing coverage scaled by group
    headcount, 80% reimbursement for emergencies at non-accredited hospitals. All of that
    is how the Bureau of Customs' published HMO procurement documents are laid out.

INVENTED, and must never be quoted as anyone's terms:
  - every peso figure that is not an MBL: the sub-limits, the outpatient ceiling, the
    first-year pre-existing caps, the co-insurance percentages
  - the members, employers, certificate numbers, dates and hotlines

Every page says so, in a banner and a watermark, because an unmarked specimen is exactly
the thing that gets mistaken for ground truth six weeks later.

Run:  python data/build_benefits_specimens.py
"""


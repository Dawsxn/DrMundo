def render_pages_as_png(pdf_path: Path) -> list:
    """Also emit page images, so the vision reader can be tested on these directly.

    The slip reader takes images, not PDFs. Without this the specimens would only be
    usable by a text extractor, which is the easy half of the problem.
    """
    import fitz

    out = []
    doc = fitz.open(pdf_path)
    for i, page in enumerate(doc):
        img = pdf_path.with_name(f"{pdf_path.stem}_p{i + 1}.png")
        page.get_pixmap(dpi=150).save(img)
        out.append(img)
    doc.close()
    return out


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    st = _styles()
    truths = []

    for name, builder in SPECIMENS:
        story, truth = builder(st)
        path = OUT_DIR / name
        _build(path, story)
        images = render_pages_as_png(path)
        truth["pages"] = len(images)
        truths.append(truth)
        print(f"  {path.name}  ({len(images)} page image(s))")

    gt = OUT_DIR / "groundtruth.json"
    gt.write_text(json.dumps(truths, indent=2), encoding="utf-8")
    print(f"  {gt.name}  ({len(truths)} specimens)")


if __name__ == "__main__":
    main()

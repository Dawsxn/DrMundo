# ----------------------------------------------------------------- page furniture
def _watermark(canvas, doc):
    """Diagonal SPECIMEN across every page, plus a footer naming the generator.

    Drawn under nothing -- it goes on top of the content deliberately. A watermark a
    screenshot can crop out is not a watermark.
    """
    canvas.saveState()
    canvas.setFont("Helvetica-Bold", 62)
    canvas.setFillColor(colors.Color(0.85, 0.87, 0.91, alpha=0.55))
    canvas.translate(A4[0] / 2, A4[1] / 2)
    canvas.rotate(38)
    canvas.drawCentredString(0, 0, "SYNTHETIC SPECIMEN")
    canvas.restoreState()

    canvas.saveState()
    canvas.setFont("Helvetica", 6.5)
    canvas.setFillColor(MUTE)
    canvas.drawString(18 * mm, 11 * mm,
                      "Synthetic test data generated by data/build_benefits_specimens.py. "
                      "Not issued by any health maintenance organisation.")
    canvas.drawRightString(A4[0] - 18 * mm, 11 * mm, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


def _styles() -> dict:
    ss = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=ss["Title"], fontSize=15, leading=19,
                                textColor=INK, spaceAfter=2),
        "sub": ParagraphStyle("s", parent=ss["Normal"], fontSize=8.5, leading=11,
                              textColor=MUTE, alignment=TA_CENTER, spaceAfter=8),
        "banner": ParagraphStyle("b", parent=ss["Normal"], fontSize=7.5, leading=9.5,
                                 textColor=colors.HexColor("#9a3412"), alignment=TA_CENTER),
        "h": ParagraphStyle("h", parent=ss["Heading2"], fontSize=10.5, leading=13,
                            textColor=ACCENT, spaceBefore=10, spaceAfter=4),
        "body": ParagraphStyle("p", parent=ss["Normal"], fontSize=8.5, leading=11.5,
                               textColor=INK, spaceAfter=4),
        "cell": ParagraphStyle("c", parent=ss["Normal"], fontSize=8, leading=10,
                               textColor=INK),
        "small": ParagraphStyle("sm", parent=ss["Normal"], fontSize=7.5, leading=9.5,
                                textColor=MUTE),
    }


def _banner_block(st: dict) -> list:
    box = Table([[Paragraph(BANNER, st["banner"])]], colWidths=[172 * mm])
    box.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#f97316")),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff7ed")),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return [box, Spacer(1, 7)]


def _table(rows: list, st: dict, widths: list, header: bool = True) -> Table:
    data = [[Paragraph(str(c), st["cell"]) for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#ecfeff")),
                  ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")]
    t.setStyle(TableStyle(style))
    return t


def _build(path: Path, story: list) -> None:
    doc = SimpleDocTemplate(
        str(path), pagesize=A4,
        leftMargin=19 * mm, rightMargin=19 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
        title=f"SYNTHETIC SPECIMEN - {path.stem}", author="build_benefits_specimens.py",
        subject="Synthetic test fixture. Not a policy document.",
    )
    doc.build(story, onFirstPage=_watermark, onLaterPages=_watermark)


